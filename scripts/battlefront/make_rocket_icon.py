"""Make the Battlefront jetpack's rocket icon (goal_src/jak3/pc/features/battlefront/battlefront-rocket-icon.gc).

The source is the mod author's golden pixel-art rocket on black (scripts/battlefront/rocket-icon.png).
Its art pixels are CELL picture pixels wide: each is sampled at its middle, the colors are reduced to
COLORS, the black is left out, and each row is cut into runs of one color. The colors are then
tinted the dark gun's purple (TINT), each keeping its brightness against the most used one. The gun HUD draws each run
as a flat rectangle (battlefront.gc `bf-draw-rocket-icon`), so the icon needs no texture.

Usage: python scripts/battlefront/make_rocket_icon.py [picture]
"""

import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "rocket-icon.png"
OUT = ROOT / "goal_src" / "jak3" / "pc" / "features" / "battlefront" / "battlefront-rocket-icon.gc"

CELL = 8     # picture pixels across one art pixel
COLORS = 6   # colors kept
BLACK = 60   # an art pixel this dark or darker is the background
TINT = (125, 102, 150)  # the dark gun's HUD icon (the game's hud-gunpurple-03a texture), round 37


def lum(c):
    """Brightness of color C (r, g, b)."""
    return 0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]


def tinted(colors, runs):
    """COLORS in TINT: the most used one (in art pixels) becomes TINT, the others as much brighter
    or darker as they were."""
    count = [0] * len(colors)
    for _, _, n, c in runs:
        count[c] += n
    ref = lum(colors[count.index(max(count))])
    return [tuple(min(255, round(t * lum(c) / ref)) for t in TINT) for c in colors]


def runs_of(src):
    """The icon's size in art pixels, its colors (r, g, b) and its runs (x, y, length, color)."""
    w, h = round(src.width / CELL), round(src.height / CELL)
    art = Image.new("RGB", (w, h))
    for y in range(h):
        for x in range(w):
            sx = min(src.width - 1, int((x + 0.5) * src.width / w))
            sy = min(src.height - 1, int((y + 0.5) * src.height / h))
            art.putpixel((x, y), src.getpixel((sx, sy)))
    q = art.quantize(colors=COLORS + 1, method=Image.Quantize.MEDIANCUT)
    pal, idx = q.getpalette(), q.load()
    used, runs = {}, []
    for y in range(h):
        x = 0
        while x < w:
            if max(art.getpixel((x, y))) <= BLACK:
                x += 1
                continue
            c, n = idx[x, y], 1
            while x + n < w and idx[x + n, y] == c and max(art.getpixel((x + n, y))) > BLACK:
                n += 1
            runs.append((x, y, n, used.setdefault(c, len(used))))
            x += n
    colors = [tuple(pal[3 * c: 3 * c + 3]) for c in sorted(used, key=used.get)]
    return w, h, colors, runs


def main():
    w, h, colors, runs = runs_of(Image.open(SRC).convert("RGB"))
    colors = tinted(colors, runs)
    assert w < 256 and h < 256 and len(colors) < 256
    words = [x | (y << 8) | (n << 16) | (c << 24) for x, y, n, c in runs]
    rgba = [r | (g << 8) | (b << 16) | (0x80 << 24) for r, g, b in colors]

    def rows(values, per):
        return "\n".join("    " + " ".join(f"#x{v:08x}" for v in values[i:i + per]) for i in range(0, len(values), per))

    OUT.write_text(f""";;-*-Lisp-*-
(in-package goal)

;; name: battlefront-rocket-icon.gc
;; name in dgo: battlefront-rocket-icon
;; dgos: GAME

#|
  Battlefront mod -- the jetpack guard's rocket icon in the gun HUD (battlefront.gc
  `bf-draw-rocket-icon`).

  GENERATED by scripts/battlefront/make_rocket_icon.py from scripts/battlefront/rocket-icon.png (the
  mod author's drawing): do not edit by hand. A {w} x {h} pixel-art picture as runs of one color,
  in the dark gun's purple.
|#

;; The icon's colors (rgba, alpha 128: opaque).
(define *bf-rocket-icon-colors*
  (new 'static 'array uint32 {len(rgba)}
{rows(rgba, 8)}
    )
  )

;; Its runs, row after row: x, y and length in art pixels, then the color's index, a byte each
;; (x | y << 8 | length << 16 | color << 24).
(define *bf-rocket-icon-runs*
  (new 'static 'array uint32 {len(words)}
{rows(words, 8)}
    )
  )

(defconstant BF_ROCKET_ICON_W {w})       ;; the icon's art pixels across
(defconstant BF_ROCKET_ICON_H {h})        ;; and down
(defconstant BF_ROCKET_ICON_RUNS {len(words)}) ;; its runs
""", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {w} x {h}, {len(colors)} colors, {len(words)} runs")


if __name__ == "__main__":
    main()
